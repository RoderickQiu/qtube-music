import Foundation

/// Read-only catalog API the UI talks to. M1: `QTMockCatalog`. M3: an InnerTube-backed implementation in QTInnerTube.
public protocol QTCatalogService: Sendable {
    func homeFeed() async throws -> QTHomeFeed
    func likedSongs() async throws -> QTPlaylist
    func libraryPlaylists() async throws -> [QTPlaylist]
    func playlist(id: String) async throws -> QTPlaylist?
    func track(videoId: String) async throws -> QTTrack?
}

public enum QTCatalogError: Error, Sendable, Equatable {
    case notFound(String)
    case unreadable(String)
}

/// The mock catalog generated by `Scripts/make-mock-catalog.py` from the prototype's 12 real tracks
/// (`Generated/MockCatalog/catalog.json` + `covers/` + `mv/`, git-ignored, bundled into the app by build-app.sh).
public struct QTMockCatalog: QTCatalogService, Sendable {
    public var tracks: [QTTrack]
    public var lyrics: [String: QTLyricsDocument]
    public var liked: QTPlaylist
    public var playlists: [QTPlaylist]
    public var home: QTHomeFeed
    /// Folder the catalog was loaded from (images resolve relative to it).
    public var root: URL?

    public init(tracks: [QTTrack], lyrics: [String: QTLyricsDocument] = [:], liked: QTPlaylist,
                playlists: [QTPlaylist] = [], home: QTHomeFeed = QTHomeFeed(), root: URL? = nil) {
        self.tracks = tracks
        self.lyrics = lyrics
        self.liked = liked
        self.playlists = playlists
        self.home = home
        self.root = root
    }

    public func track(id: String) -> QTTrack? { tracks.first { $0.videoId == id } }

    // MARK: QTCatalogService

    public func homeFeed() async throws -> QTHomeFeed { home }
    public func likedSongs() async throws -> QTPlaylist { liked }
    public func libraryPlaylists() async throws -> [QTPlaylist] { playlists }
    public func playlist(id: String) async throws -> QTPlaylist? {
        id == liked.id ? liked : playlists.first { $0.id == id }
    }
    public func track(videoId: String) async throws -> QTTrack? { track(id: videoId) }

    // MARK: Loading

    public static let fileName = "catalog.json"
    /// Folder name inside the app's Resources and under `Generated/`.
    public static let folderName = "MockCatalog"

    /// Loads `<folder>/catalog.json`, resolving relative image paths against `folder`.
    public static func load(from folder: URL) throws -> QTMockCatalog {
        let url = folder.appendingPathComponent(fileName)
        guard let data = try? Data(contentsOf: url) else { throw QTCatalogError.notFound(url.path) }
        let file: QTMockCatalogFile
        do {
            file = try JSONDecoder().decode(QTMockCatalogFile.self, from: data)
        } catch {
            throw QTCatalogError.unreadable("\(url.path): \(error)")
        }
        return file.resolve(root: folder)
    }

    /// Finds the catalog: explicit path → `$QT_MOCK_CATALOG` → app bundle Resources → `<repo>/Generated/MockCatalog`.
    public static func locate(explicitPath: String? = nil, bundle: Bundle = .main,
                              environment: [String: String] = ProcessInfo.processInfo.environment,
                              sourceFile: String = #filePath) -> URL? {
        var candidates: [URL] = []
        if let p = explicitPath, !p.isEmpty { candidates.append(URL(fileURLWithPath: (p as NSString).expandingTildeInPath)) }
        if let p = environment["QT_MOCK_CATALOG"], !p.isEmpty { candidates.append(URL(fileURLWithPath: p)) }
        if let res = bundle.resourceURL { candidates.append(res.appendingPathComponent(folderName)) }
        // Dev fallback: Sources/QTCore/Catalog/QTMockCatalog.swift → repo root.
        let repo = URL(fileURLWithPath: sourceFile).deletingLastPathComponent().deletingLastPathComponent()
            .deletingLastPathComponent().deletingLastPathComponent()
        candidates.append(repo.appendingPathComponent("Generated").appendingPathComponent(folderName))
        return candidates.first { FileManager.default.fileExists(atPath: $0.appendingPathComponent(fileName).path) }
    }
}

// MARK: - File format (written by Scripts/make-mock-catalog.py)

/// On-disk shape: tracks once, everything else by id; image paths relative to the catalog folder.
struct QTMockCatalogFile: Decodable {
    struct PlaylistEntry: Decodable {
        var id: String
        var title: QTDisplayText
        var kind: QTPlaylistKind
        var owner: String?
        var artwork: [QTArtworkImage]?
        var trackIDs: [String]
    }

    struct ShelfItemEntry: Decodable {
        var track: String?
        var video: String?
        var playlist: String?
    }

    struct ShelfEntry: Decodable {
        var id: String
        var title: QTDisplayText
        var style: QTShelfStyle
        var items: [ShelfItemEntry]
    }

    struct HomeEntry: Decodable {
        var moods: [QTMoodChip]
        var shelves: [ShelfEntry]
    }

    var version: Int
    var tracks: [QTTrack]
    var lyrics: [String: QTLyricsDocument]
    var liked: PlaylistEntry
    var playlists: [PlaylistEntry]
    var home: HomeEntry

    func resolve(root: URL) -> QTMockCatalog {
        func fix(_ images: [QTArtworkImage]) -> [QTArtworkImage] {
            images.map { img in
                var img = img
                if img.url.scheme == nil { img.url = root.appendingPathComponent(img.url.relativeString) }
                return img
            }
        }
        let resolvedTracks: [QTTrack] = tracks.map { t in
            var t = t
            t.artwork = fix(t.artwork)
            if var c = t.counterpart { c.artwork = fix(c.artwork); t.counterpart = c }
            return t
        }
        let byID = Dictionary(resolvedTracks.map { ($0.videoId, $0) }, uniquingKeysWith: { a, _ in a })
        func playlist(_ e: PlaylistEntry) -> QTPlaylist {
            let ts = e.trackIDs.compactMap { byID[$0] }
            return QTPlaylist(id: e.id, title: e.title, kind: e.kind, owner: e.owner,
                              artwork: fix(e.artwork ?? []), tracks: ts)
        }
        let likedList = playlist(liked)
        let lists = playlists.map(playlist)
        let listByID = Dictionary((lists + [likedList]).map { ($0.id, $0) }, uniquingKeysWith: { a, _ in a })
        let shelves = home.shelves.map { s in
            QTShelf(id: s.id, title: s.title, style: s.style, items: s.items.compactMap { i -> QTShelfItem? in
                if let id = i.track, let t = byID[id] { return .track(t) }
                if let id = i.video, let t = byID[id] { return .video(t) }
                if let id = i.playlist, let p = listByID[id] { return .playlist(p) }
                return nil
            })
        }
        return QTMockCatalog(tracks: resolvedTracks, lyrics: lyrics, liked: likedList, playlists: lists,
                             home: QTHomeFeed(moods: home.moods, shelves: shelves), root: root)
    }
}
